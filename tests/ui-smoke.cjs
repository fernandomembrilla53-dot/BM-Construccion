"use strict";
const {chromium}=require("playwright");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const base="http://127.0.0.1:8765/";
(async()=>{
 const browser=await chromium.launch({headless:true});
 const output=path.resolve("store-assets/screenshots");fs.mkdirSync(output,{recursive:true});
 const errors=[];
 const desktop=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1,acceptDownloads:true});
 desktop.on("pageerror",e=>errors.push("desktop: "+e.message));
 await desktop.goto(base,{waitUntil:"networkidle"});
 await desktop.locator("#results .result-metric").first().waitFor();
 assert.match(await desktop.locator("#tool-title").innerText(),/Ladrillos/);
 assert.equal(await desktop.locator(".tool-link").count(),11);
 assert.match(await desktop.locator(".result-metric.primary .result-value").first().innerText(),/990/);
 await desktop.screenshot({path:path.join(output,"desktop-inicio.png"),fullPage:true});
 await desktop.locator("#project-name").fill("Proyecto de muestra");
 await desktop.locator("#project-name").dispatchEvent("change");
 await desktop.locator("#save-result").click();
 assert.match(await desktop.locator("#saved-count").innerText(),/1/);
 const downloadPromise=desktop.waitForEvent("download");
 await desktop.locator("#export-csv").click();
 const download=await downloadPromise;
 assert.ok(download.suggestedFilename().endsWith(".csv"));
 await desktop.locator("#view-history").click();
 assert.equal(await desktop.locator("#history-dialog").evaluate(el=>el.open),true);
 await desktop.locator("#close-history").click();
 await desktop.locator("[data-tool=pisos]").click();
 assert.match(await desktop.locator("#tool-title").innerText(),/Pisos/);
 assert.match(await desktop.locator(".result-metric.primary .result-value").first().innerText(),/11/);
 await desktop.locator("#f-boxArea").fill("0");
 await desktop.locator("#calc-form button[type=submit]").click();
 assert.equal(await desktop.locator("#calc-error").isVisible(),true);
 await desktop.locator("#f-boxArea").fill("2");
 await desktop.locator("#calc-form button[type=submit]").click();
 assert.equal(await desktop.locator("#calc-error").isVisible(),false);
 const mobile=await browser.newPage({viewport:{width:390,height:694},deviceScaleFactor:3,isMobile:true,hasTouch:true,acceptDownloads:true});
 mobile.on("pageerror",e=>errors.push("mobile: "+e.message));
 await mobile.goto(base,{waitUntil:"networkidle"});
 await mobile.locator("#results .result-metric").first().waitFor();
 await mobile.screenshot({path:path.join(output,"01-inicio-movil.png")});
 await mobile.locator("#workspace").scrollIntoViewIfNeeded();
 await mobile.screenshot({path:path.join(output,"02-muros-movil.png")});
 await mobile.locator("[data-tool=pisos]").click();
 await mobile.locator("#workspace").scrollIntoViewIfNeeded();
 await mobile.screenshot({path:path.join(output,"03-pisos-movil.png")});
 await mobile.locator("[data-tool=hierro]").click();
 await mobile.locator("#workspace").scrollIntoViewIfNeeded();
 await mobile.screenshot({path:path.join(output,"04-hierro-movil.png")});
 const dims=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:window.innerWidth}));
 assert.ok(dims.scroll <= dims.width+2,"Desborde horizontal: "+JSON.stringify(dims));
 const canOffline=await mobile.evaluate(async()=>{if(!("serviceWorker" in navigator))return false;await navigator.serviceWorker.ready;return true;});
 assert.ok(canOffline,"Falta registrar el service worker");
 await mobile.context().setOffline(true);
 await mobile.reload({waitUntil:"domcontentloaded"});
 await mobile.locator("#tool-title").waitFor();
 assert.match(await mobile.locator("#tool-title").innerText(),/Hierro|Ladrillos/);
 await mobile.context().setOffline(false);
 assert.deepEqual(errors,[]);
 console.log("PRUEBAS UI OK: calculadoras, validación, presupuesto, exportación CSV, modal, móvil y modo sin conexión.");
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
